"""Refresh the executable's source identity without touching unchanged headers."""
import argparse
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    def git(*arguments):
        return subprocess.check_output(["git", *arguments], cwd=ROOT, text=True).strip()
    source = git("rev-parse", "HEAD")
    # Dependencies intentionally contain the committed patch stack. The release
    # packager checks their complete patched trees separately.
    dirty = bool(git("status", "--porcelain", "--untracked-files=normal", "--ignore-submodules=dirty"))
    content = ("// Generated by write_build_identity.py.\n#pragma once\nnamespace build_identity {\n"
               f'inline constexpr char source[] = "{source}";\n'
               f'inline constexpr bool dirty = {str(dirty).lower()};\n' + "}\n")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text(encoding="utf-8") != content:
        with args.output.open("w", encoding="utf-8", newline="\n") as output:
            output.write(content)


if __name__ == "__main__":
    main()
